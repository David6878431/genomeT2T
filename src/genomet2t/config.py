"""Read TOML as data, validate selected steps, and emit quoted Bash assignments."""
from dataclasses import dataclass
import json
from pathlib import Path, PurePosixPath
import re
import shlex
import tomllib

from .assets import workflow_directory
from .stages import Stage


class ConfigError(ValueError):
    pass


WORD_LISTS = {"QUAL_MODULES", "BUSCO_LINEAGES"}
BASH_ARRAYS = {"TRNASCAN_OPTIONS"}
DIRECTORIES = {"workdir", "datadir", "database", "scriptsdir"}
FILE_KEYS = {
    "ILLUMINA_R1", "ILLUMINA_R2", "HIFI_READS", "ONT_READS", "ONT_FASTA",
    "RNASEQ_R1", "RNASEQ_R2", "HIC_R1", "HIC_R2", "POLISH_INPUT",
    "INPUT_CONTIGS", "SCAFFOLD_CONTIGS", "SCAFFOLD_FASTA", "FINAL_ASSEMBLY",
    "GAPFILL_ASSEMBLY", "CONTAMINANT_FASTA", "ORGANELLE_FASTA", "RRNA45S_FASTA",
    "REF_GENOME", "REF_GFF", "LIFTOFF_CHROM_MAP", "CHROMOSOME_MAP",
    "HOMOLOGY_REFERENCES", "GEMOMA_JAR", "VISUALIZER", "REPEATMASKER_LIB",
    "SPROT_CLEAN", "UNIPROT_FASTA", "UNIPROT_DIAMOND", "BUSCO_PLOT",
    "TRUSTED_TRANSCRIPTS", "RACON", "INTERPROSCAN",
}
PATH_KEYS = FILE_KEYS | DIRECTORIES | {
    "SOFTWARE_DIR", "REPEATMASKER_DIR", "TRANSDECODER_UTIL", "GENOMETOOLS_BIN",
}
POSITIVE = {
    "threads", "GENOME_SIZE", "PLOIDY", "KMER_SIZE", "CHROMOSOME_COUNT",
    "NEXTDENOVO_JOBS", "NEXTPOLISH_JOBS", "CENTROMERE_MIN", "CENTROMERE_MAX",
    "GAPFILL_MIN_READS", "GAPFILL_MIN_MATCH", "MERQURY_K", "KMER_HIST_MAX",
    "ORF_MIN_AA", "CIRCOS_WINDOW",
}
ALIASES = {"WORKDIR": "workdir", "DATADIR": "datadir", "DATABASE_DIR": "database",
           "SCRIPTS_DIR": "scriptsdir", "THREADS": "threads", "SPECIES_PREFIX": "species"}


def defaults() -> dict:
    """Read literal assignments from our bundled shell template, never execute it."""
    values = {}
    for line in (workflow_directory() / "config.example.sh").read_text(encoding="utf-8").splitlines():
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line)
        if not match:
            continue
        key, raw = match.groups()
        if raw.startswith("(") and raw.endswith(")"):
            value = shlex.split(raw[1:-1], comments=True)
        else:
            parts = shlex.split(raw, comments=True)
            if len(parts) > 1:
                raise ConfigError(f"Template assignment {key} is not a literal scalar.")
            value = parts[0] if parts else ""
            if value.isdecimal():
                value = int(value)
            if key in WORD_LISTS:
                value = str(value).split()
            if key in BASH_ARRAYS:
                value = shlex.split(str(value))
        values[key] = value
    return values


def example_toml() -> str:
    lines = [
        "# genomeT2T configuration. Replace REPLACE_ME before the relevant step.",
        "# Pipeline paths are inside the container when using --executor docker.",
        "# Docker host paths are relative to this TOML file, or absolute paths.",
        "[pipeline]",
    ]
    for key, value in defaults().items():
        lines.append(f"{key} = {json.dumps(value, ensure_ascii=False)}")
    lines += [
        "",
        "[docker]",
        'workdir = "./results"',
        'datadir = "./data"',
        'database = "./database"',
        'helpers = ""  # Optional; overrides the image directory /work/script.',
        'assembly_image = "omicsclass/genome-t2t:v1.0"',
        'annotation_image = "omicsclass/genome-annotation:v1.0"',
        "",
    ]
    return "\n".join(lines)


def unresolved(value) -> bool:
    return value is None or value == "" or value == [] or "REPLACE_ME" in str(value)


@dataclass
class PipelineConfig:
    path: Path
    pipeline: dict
    docker: dict

    def shell_text(self, executor: str) -> str:
        lines = ["# Generated by genomet2t; values are shell-quoted data."]
        for key, value in self.pipeline.items():
            if key in BASH_ARRAYS:
                items = value if isinstance(value, list) else shlex.split(str(value))
                encoded = "(" + " ".join(shlex.quote(str(item)) for item in items) + ")"
            else:
                if isinstance(value, list):
                    value = " ".join(str(item) for item in value)
                if key in PATH_KEYS and value and not unresolved(value):
                    if executor == "local":
                        value = self.local_path(str(value)).as_posix()
                    elif not PurePosixPath(str(value)).is_absolute():
                        raise ConfigError(f"{key} must be an absolute container path for Docker.")
                encoded = shlex.quote(str(value))
            lines.append(f"{key}={encoded}")
        return "\n".join(lines) + "\n"

    def local_path(self, value: str) -> Path:
        path = Path(value).expanduser()
        return path.resolve() if path.is_absolute() else (self.path.parent / path).resolve()

    def host_mounts(self) -> list[tuple[Path, str]]:
        result = []
        for key, container_key in (("workdir", "workdir"), ("datadir", "datadir"),
                                   ("database", "database"), ("helpers", "scriptsdir")):
            value = self.docker.get(key, "")
            if not value:
                if key == "helpers":
                    continue
                raise ConfigError(f"[docker].{key} must name a host directory.")
            target = str(self.pipeline[container_key])
            if not PurePosixPath(target).is_absolute() or target == "/":
                raise ConfigError(f"pipeline.{container_key} must be an absolute non-root container path.")
            reserved = {"/opt/genomet2t", "/opt/genomet2t-config.sh"}
            if any(target.rstrip("/") == p or p.startswith(target.rstrip("/") + "/")
                   or target.startswith(p + "/") for p in reserved):
                raise ConfigError(f"Reserved container mount target: {target}")
            result.append((self.local_path(value), target.rstrip("/")))
        targets = [target for _, target in result]
        if len(targets) != len(set(targets)):
            raise ConfigError("Docker mount destinations must be distinct.")
        for target in targets:
            if any(other != target and target.startswith(other + "/") for other in targets):
                raise ConfigError("Docker mount destinations cannot contain each other.")
        return result

    def validate(self, stages: list[Stage], executor: str, check_files: bool = False) -> None:
        errors = []
        if executor not in {"local", "docker"}:
            raise ConfigError("Executor must be 'local' or 'docker'.")
        for key in DIRECTORIES | {"threads"}:
            if unresolved(self.pipeline.get(key)):
                errors.append(f"Set pipeline.{key} before running.")
        for key, value in self.pipeline.items():
            if key in POSITIVE and not unresolved(value):
                if isinstance(value, bool) or not str(value).isdigit() or int(value) < 1:
                    errors.append(f"{key} must be a positive integer.")
            if key in DIRECTORIES and any(c.isspace() for c in str(value)):
                errors.append(f"{key} cannot contain whitespace (legacy Bash tools).")
            if "\0" in str(value) or "\n" in str(value) or "\r" in str(value):
                errors.append(f"{key} cannot contain NUL or newline characters.")
        for stage in stages:
            required = list(stage.required)
            if stage.name == "gapfill":
                mode = self.pipeline.get("GAPFILL_MODE")
                if mode not in {"reads", "assembly"}:
                    errors.append("GAPFILL_MODE must be 'reads' or 'assembly'.")
                required += ["ONT_READS", "RACON"] if mode == "reads" else ["GAPFILL_ASSEMBLY"]
            if stage.name == "assess":
                modules = self.pipeline.get("QUAL_MODULES", [])
                if isinstance(modules, str):
                    modules = modules.split()
                allowed = {"stats", "mapping", "merqury", "lai", "busco"}
                for module in modules:
                    if module not in allowed:
                        errors.append(f"Unknown quality module: {module}")
                if "busco" in modules:
                    required += ["BUSCO_LINEAGES"]
                if "mapping" in modules:
                    required += ["ILLUMINA_R1", "ILLUMINA_R2", "HIFI_READS"]
                if "merqury" in modules:
                    required += ["HIFI_READS", "MERQURY_K"]
            for key in required:
                value = self.pipeline.get(key)
                if unresolved(value):
                    errors.append(f"{stage.name}: set pipeline.{key} before running.")
                elif check_files and executor == "local" and key in FILE_KEYS:
                    if not self.local_path(str(value)).is_file():
                        errors.append(f"{stage.name}: file does not exist: {value}")
            job_key = {"ont": "NEXTDENOVO_JOBS", "ont-polish": "NEXTPOLISH_JOBS",
                       "polish": "NEXTPOLISH_JOBS"}.get(stage.name)
            if job_key and not unresolved(self.pipeline.get(job_key)):
                try:
                    if int(self.pipeline[job_key]) > int(self.pipeline["threads"]):
                        errors.append(f"{job_key} cannot exceed threads.")
                except (ValueError, TypeError):
                    pass  # Integer validation above gives the detailed error.
        if executor == "docker":
            mounts = self.host_mounts()
            if check_files:
                for host, _ in mounts:
                    if not host.is_dir():
                        errors.append(f"Docker host directory does not exist: {host}")
        if errors:
            raise ConfigError("\n".join(dict.fromkeys(errors)))
        self.shell_text(executor)


def load_config(path: str | Path) -> PipelineConfig:
    path = Path(path).expanduser().resolve()
    try:
        raw = tomllib.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, tomllib.TOMLDecodeError) as error:
        raise ConfigError(f"Cannot read TOML config {path}: {error}") from error
    if set(raw) - {"pipeline", "docker"}:
        raise ConfigError("Only [pipeline] and [docker] tables are supported.")
    if not isinstance(raw.get("pipeline"), dict):
        raise ConfigError("Config must contain a [pipeline] table.")
    known = defaults()
    pipeline = dict(known)
    seen = set()
    for key, value in raw["pipeline"].items():
        key = ALIASES.get(key, key)
        if key not in known:
            raise ConfigError(f"Unknown pipeline setting {key!r}.")
        if key in seen:
            raise ConfigError(f"Duplicate setting via uppercase/lowercase alias: {key}")
        seen.add(key)
        if isinstance(value, bool) or not isinstance(value, (str, int, float, list)):
            raise ConfigError(f"{key} must be a scalar or supported string list.")
        if key in PATH_KEYS and not isinstance(value, str):
            raise ConfigError(f"{key} must be a path string.")
        if key in WORD_LISTS | BASH_ARRAYS and not isinstance(value, (str, list)):
            raise ConfigError(f"{key} must be a string or a string list.")
        if isinstance(value, list):
            if key not in WORD_LISTS | BASH_ARRAYS or not all(isinstance(v, str) for v in value):
                raise ConfigError(f"{key} does not accept this list.")
        pipeline[key] = value
    docker = raw.get("docker", {})
    if not isinstance(docker, dict) or set(docker) - {
        "workdir", "datadir", "database", "helpers", "assembly_image", "annotation_image"
    } or not all(isinstance(v, str) for v in docker.values()):
        raise ConfigError("Invalid [docker] setting; use 'genomet2t init' for the schema.")
    return PipelineConfig(path, pipeline, docker)
